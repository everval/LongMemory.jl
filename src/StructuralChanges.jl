"""
# StructuralChanges

This module contains functions to estimate structural changes in models containing long memory errors.

## Author

[J. Eduardo Vera-Valdés](https://everval.github.io/)

"""
module StructuralChanges

using ..LogPeriodEstimators: exact_whittle_est, whittle_est, periodogram, freq_band
using ..GeneratingFunctions: fracdiff, fi_gen
using ..ClassicEstimators: smean

using FFTW

export lm_change_test, qu_test

"""
    lm_change_test(y::AbstractArray; uplim::Real = 0.15, lowlim::Real = 0.15, flag::Bool = false, nsim::Int = 199)

Estimates the location of a structural change in a long memory model.

# Arguments
- `y::Array`: The series to be tested.

# Optional arguments
- `uplim::Real = 0.15`: The upper limit of the fraction of the series to be tested.
- `lowlim::Real = 0.15`: The lower limit of the fraction of the series to be tested.
- `flag::Bool = false`: If true, the test statistic and a Monte Carlo p-value are also returned.
- `nsim::Int = 199`: The number of Monte Carlo replications used for the p-value when `flag = true`.

# Output
- `τ::Int`: The estimated location of the structural change.
- `stat::Real`: The test statistic, the maximum of the forward and backward squared t-statistics. Only if `flag = true`.
- `pval::Real`: The Monte Carlo p-value. Only if `flag = true`.

# Examples
```julia-repl
julia> lm_change_test(randn(100))
```

# Notes
The function estimates the location of a structural change in a long memory model. The function uses the Whittle estimator to estimate the long memory parameter. Then, it fractionally differences the demeaned series and computes the t-statistics of the OLS regression of the differenced series on the starred series. The function computes the forward and backward t-statistics and returns the location of the maximum squared t-statistic. Hence, it is robust to the direction of the change.

The p-value is computed by parametric bootstrap: the statistic is recomputed, including the estimation of `d`, on `nsim` series simulated with `fi_gen` under the null of a constant long memory parameter equal to the estimate. Hence, it is random; fix the seed for reproducibility.
In simulations with `T = 300` and `d = 0.3`, the test rejected about 7% of the time at the nominal 5% level, so it is slightly liberal in small samples.

# References
Martins and Rodrigues (2014), "Testing for persistence change in fractionally integrated models: An application to world inflation rates", Computational Statistics and Data Analysis, 76.
"""
function lm_change_test(y::AbstractArray; uplim::Real = 0.15, lowlim::Real = 0.15, flag::Bool = false, nsim::Int = 199)
    T = length(y)

    τ, stat, d0 = lm_change_stat(y, uplim, lowlim)

    if flag == false
        return τ
    end

    sims = zeros(nsim)
    for ii = 1:nsim
        sims[ii] = lm_change_stat(fi_gen(T, d0), uplim, lowlim)[2]
    end

    pval = (1 + sum(sims .>= stat)) / (nsim + 1)

    return τ, stat, pval
end


"""
    qu_test(x::AbstractArray; m::Real = 0.7, ε::Real = 0.05)

Computes the test of Qu (2011) of the null hypothesis of a stationary long memory process against the alternative of spurious long memory, such as that generated by level shifts or smooth trends.

# Arguments
- `x::Array`: The time series.

# Optional arguments
- `m::Real = 0.7`: The bandwidth exponent; the `round(T^m)` lowest Fourier frequencies are used.
- `ε::Real = 0.05`: The trimming parameter, either 0.02 or 0.05.

# Output
- `W::Real`: The test statistic.
- `crit::Array`: The asymptotic critical values at the 10%, 5%, and 1% levels.

# Notes
The statistic is `W = sup_{r∈[ε,1]} |Σ_{j≤mr} ν_j (I_j λ_j^{2d}/G - 1)| / (Σ_j ν_j²)^{1/2}`, with `d` and `G` the local Whittle estimates (see `whittle_est`) and `ν_j = log λ_j - mean(log λ)`. It compares the local Whittle score at different bandwidths: under spurious long memory the periodogram does not follow the power law at the lowest frequencies.
The null is rejected for large values of `W`.

# References
Qu, Z. (2011). A test against spurious long memory. Journal of Business & Economic Statistics, 29(3), 423-438.

# Examples
```julia-repl
julia> qu_test(fi_gen(1000, 0.3))
```
"""
function qu_test(x::AbstractArray; m::Real = 0.7, ε::Real = 0.05)
    if ε == 0.02
        crit = [1.118, 1.252, 1.517]
    elseif ε == 0.05
        crit = [1.022, 1.155, 1.426]
    else
        error("Critical values are only available for ε = 0.02 and ε = 0.05")
    end

    T = length(x)
    band = freq_band(T, m, 0)

    I_w0, w0 = periodogram(x)
    I_w = I_w0[band]
    w = w0[band]
    nm = length(w)

    d = whittle_est(x; m=m)
    G = smean(I_w .* w .^ (2 * d))

    ν = log.(w) .- smean(log.(w))
    aux = cumsum(ν .* (I_w .* w .^ (2 * d) ./ G .- 1))

    r0 = max(floor(Int, ε * nm), 1)
    W = maximum(abs.(aux[r0:nm])) / sqrt(sum(ν .^ 2))

    return W, crit
end


## Internal functions
"""
    lm_change_stat(y::AbstractArray, uplim::Real, lowlim::Real)

Computes the location of the structural change, the test statistic, and the estimate of `d` used in `lm_change_test`. Internal function.
"""
function lm_change_stat(y::AbstractArray, uplim::Real, lowlim::Real)
    T = length(y)
    Λₗ = round(Int, T*lowlim)
    Λᵤ = round(Int, T*(1-uplim))

    # Estimate the long memory parameter
    d0 = exact_whittle_est(y)

    # Fractionally differencing the demeaned series to I(0) under the null
    x = fracdiff(y .- smean(y), d0)
    xstar = starred_var(x)

    # Forward direction
    tvalsup = zeros(Λᵤ - Λₗ + 1, 1)
    for ii in Λₗ:Λᵤ
        tvalsup[ii-Λₗ+1] = simple_ols(x[2:ii], xstar[1:(ii-1)])
    end

    # Backward direction
    w = reverse(x)
    wstar = starred_var(w)
    tvalsdown = zeros(Λᵤ - Λₗ + 1, 1)
    for ii in Λₗ:Λᵤ
        tvalsdown[ii-Λₗ+1] = simple_ols(w[2:ii], wstar[1:(ii-1)])
    end

    tvals = [tvalsup.^2 tvalsdown.^2]

    stat, idx = findmax(tvals)
    ii = idx[1] + Λₗ - 1

    # The backward statistic at ii uses the last ii observations, so the break is at T - ii in the original time index
    τ = idx[2] == 1 ? ii : T - ii

    return τ, stat, d0
end

"""
    starred_var(x::AbstractArray)

Computes the padded series `x` with detrending coefficients.

# Arguments
- `x::Array`: The series to be detrended.

# Output
- `dx::Array`: The detrended series.
"""
function starred_var(x::AbstractArray)
    T = length(x)

    np2 = nextpow(2, 2 * T - 1)

    coefs = collect(1 ./ (1:(T-1)))

    padcoefs = [coefs; zeros(np2 - T + 1, 1)]
    padx = [x[1:(T-1)]; zeros(np2 - T + 1, 1)]

    dx = irfft(rfft(padx) .* rfft(padcoefs), np2)
    return dx[1:(T-1)]
end

"""
    simple_ols(y::AbstractArray, x::AbstractArray)

Computes the t-statistics of the OLS regression of `y` on `x`.

# Arguments
- `y::Array`: The dependent variable.
- `x::Array`: The independent variable.

# Output
- `tstat::Array`: The t-statistic of the regression.

# Notes
The function should only be used internally. It is not exported. It is used to compute the t-statistics of the OLS regression in the `lm_change_test` function. Hence, it does not adds intercepts to the regression nor it returns the coefficient.
"""
function simple_ols(y::AbstractArray, x::AbstractArray)
    T = length(y)
    β = x\y

    err = y-x*β
    σ² = (err'*err)/(T-1)
    tstat = β/sqrt(σ²/(x'*x))

    return tstat
end

end # module